"""Pre-registered hypothesis tests for a real-network evening (docs/PREREGISTRATION_DAY<n>.md).

  python scripts/preregistered_tests.py            # second evening -> docs/results/preregistered_day2.md
  python scripts/preregistered_tests.py --day 3    # third evening  -> docs/results/preregistered_day3.md

Per-block alert rates are averaged over seeds, then compared with a two-sided sign test over blocks (ties dropped).
Detection change is the mean per-seed difference in benchmark class-balanced detection. Reads only committed
result files, so every number in the confirmation section can be regenerated.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
from scipy.stats import binomtest

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "docs/results"
FEW_SHOT = "few-shot"
REPAIR = "few-shot + 30 triaged local flows + exemplar envelope"
LAB = "few-shot + 30 lab service flows"
EXPLORATORY = ["few-shot + 30 triaged local flows + local anomaly threshold",
               "few-shot + 30 triaged local flows + local refit anomaly",
               "few-shot + 30 triaged local flows + two-envelope anomaly",
               "few-shot + 30 uncertain local flows + exemplar envelope"]


def block_rates(res: dict, config: str) -> np.ndarray:
    return np.mean([r["real_network"]["block_rates"] for r in res["runs"] if r["config"] == config], axis=0)


def detection_change(res: dict, config: str, reference: str) -> float:
    det = {c: {r["seed"]: r["target_test"]["macro_detection"] for r in res["runs"] if r["config"] == c}
           for c in (config, reference)}
    return float(np.mean([det[config][s] - det[reference][s] for s in det[reference]]))


def sign_test(a: np.ndarray, b: np.ndarray) -> dict:
    """Two-sided sign test of a against b over blocks; ties dropped."""
    d = np.asarray(a) - np.asarray(b)
    lower, higher = int((d < 0).sum()), int((d > 0).sum())
    p = binomtest(lower, lower + higher, 0.5).pvalue if lower + higher else 1.0
    return {"lower": lower, "higher": higher, "ties": int((d == 0).sum()), "p": float(p)}


def evaluate(res: dict) -> dict:
    base, rep = block_rates(res, FEW_SHOT), block_rates(res, REPAIR)
    return {"repair": sign_test(rep, base), "detection_change": detection_change(res, REPAIR, FEW_SHOT),
            "lab": sign_test(block_rates(res, LAB), base),
            "exploratory": {c: sign_test(rep, block_rates(res, c)) for c in EXPLORATORY}}


def fmt(t: dict) -> str:
    return f"lower {t['lower']}, higher {t['higher']}, ties {t['ties']}, p = {t['p']:.4f}"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--day", type=int, default=2, choices=[2, 3])
    day = ap.parse_args().day
    name = {2: "second", 3: "third"}[day]
    lines = [f"# Pre-registered tests, {name} evening", "",
             f"Generated by `scripts/preregistered_tests.py --day {day}` from the day-{day} result files; rules in "
             f"[PREREGISTRATION_DAY{day}.md](../PREREGISTRATION_DAY{day}.md).", "",
             "| Features | Repair vs few-shot | Detection change | Lab flows vs few-shot |",
             "|---|---|---|---|"]
    explore = []
    for label, suffix in [("Without port and window features", "_portable"), ("All 83 features", "")]:
        out = evaluate(json.loads((RES / f"real_network_day{day}{suffix}.json").read_text(encoding="utf-8")))
        lines.append(f"| {label} | {fmt(out['repair'])} | {out['detection_change']:+.4f} | {fmt(out['lab'])} |")
        explore += [f"| {label} | {c.removeprefix('few-shot + 30 ')} | {fmt(t)} |" for c, t in out["exploratory"].items()]
    lines += ["", "## Exploratory: triage + exemplar envelope against each alternative", "",
              "| Features | Alternative | Exemplar repair lower / higher |", "|---|---|---|", *explore, ""]
    (RES / f"preregistered_day{day}.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
