"""Leave-one-attack-out evaluation (RQ3): can the detector flag an attack class it never saw in training?

Usage:
  python scripts/unseen_attack_eval.py data/processed/cicids2017.parquet --model lgbm --cap 60000 \
      --results docs/results/unseen_cicids2017.md

For each attack class C, the class is removed from training and validation entirely, a detector
(classifier + benign-only Isolation Forest, threshold tuned on validation benign flows to a 1% FPR)
is trained on what remains, and every flow of C in the dataset is scored. A reference model trained
on all classes gives the "seen" detection rate on the same test split for comparison.

An unseen flow counts as detected when the classifier calls it any attack class, or the Isolation
Forest flags it as an outlier (the deployed alert rule). We also record which known class it was
mistaken for: an unseen DDoS labelled "DoS-Hulk" still raises a useful alert in the right ATT&CK family.
"""
import argparse
import json
import time
from pathlib import Path

import pandas as pd

from ids.data import BENIGN, LABEL_COL, dedup_global, feature_columns, stratified_sample, temporal_split
from ids.evaluate import binary_report
from ids.models import Detector


def fit(train: pd.DataFrame, val: pd.DataFrame, feats: list[str], model: str, log: bool) -> Detector:
    det = Detector(model, anomaly_log=log).fit(train[feats], train[LABEL_COL])
    det.fit_anomaly(train[train[LABEL_COL] == BENIGN][feats])
    det.tune_anomaly_threshold(val[val[LABEL_COL] == BENIGN][feats])
    return det


def detection(det: Detector, X: pd.DataFrame) -> dict:
    pred = det.predict(X)
    _, outlier = det.anomaly(X)
    by_clf = pred != BENIGN
    mistaken = pd.Series(pred[by_clf]).value_counts()
    return {"flows": len(X), "classifier": float(by_clf.mean()), "anomaly": float(outlier.mean()),
            "either": float((by_clf | outlier).mean()),
            "mistaken_for": mistaken.head(3).to_dict()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("parquet")
    ap.add_argument("--model", default="lgbm")
    ap.add_argument("--cap", type=int, default=60000)
    ap.add_argument("--min-flows", type=int, default=10, help="skip classes with fewer flows than this")
    ap.add_argument("--anomaly-log", action="store_true", help="signed log transform before the Isolation Forest")
    ap.add_argument("--results", default="docs/results/unseen.md")
    args = ap.parse_args()

    t0 = time.perf_counter()
    df = dedup_global(pd.read_parquet(args.parquet))
    feats = feature_columns(df)
    train, val, test = temporal_split(df)
    train = stratified_sample(train, args.cap)
    test_benign = test[test[LABEL_COL] == BENIGN]
    counts = df[LABEL_COL].value_counts()
    attacks = [c for c in counts.index if c != BENIGN and counts[c] >= args.min_flows]
    name = Path(args.parquet).stem

    ref = fit(train, val, feats, args.model, args.anomaly_log)
    rows = []
    for c in attacks:
        t = time.perf_counter()
        det = fit(train[train[LABEL_COL] != c], val[val[LABEL_COL] != c], feats, args.model, args.anomaly_log)
        unseen = detection(det, df[df[LABEL_COL] == c][feats])
        seen = detection(ref, test[test[LABEL_COL] == c][feats])
        _, out = det.anomaly(test_benign[feats])
        cost = binary_report(test_benign[LABEL_COL], (det.predict(test_benign[feats]) != BENIGN) | out)
        rows.append({"class": c, "unseen": unseen, "seen_classifier": seen["classifier"], "benign_fpr": cost["fpr"]})
        print(f"{c}: unseen detected {unseen['either']:.3f} (clf {unseen['classifier']:.3f}, "
              f"iforest {unseen['anomaly']:.3f}) | seen {seen['classifier']:.3f} | "
              f"{time.perf_counter() - t:.0f}s", flush=True)

    res = {"dataset": name, "generated": time.strftime("%Y-%m-%d"), "model": args.model, "cap": args.cap,
           "anomaly_target_fpr": 0.01, "anomaly_log": args.anomaly_log, "results": rows, "minutes": (time.perf_counter() - t0) / 60}
    out = Path(args.results)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.with_suffix(".json").write_text(json.dumps(res, indent=1), encoding="utf-8")

    md = [f"# Unseen-attack (leave-one-attack-out) evaluation: {name}", "",
          f"Generated by `python scripts/unseen_attack_eval.py {args.parquet} --model {args.model} --cap {args.cap}` "
          f"{' --anomaly-log' if args.anomaly_log else ''} on {res['generated']}. For each attack class, a {args.model.upper()} classifier and a benign-only "
          f"Isolation Forest{' on signed-log features' if args.anomaly_log else ''} (threshold tuned on validation benign flows to a 1% false-positive rate) are trained "
          "**without that class**, then every flow of the class is scored. *Seen* is the detection rate of a "
          "model trained on all classes, on the same class's test flows.", "",
          "| Held-out class | Flows | Detected (classifier or anomaly) | Classifier only | Isolation Forest only | "
          "Seen-class detection | Benign FPR | Mostly mistaken for |", "|---|---|---|---|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: -r["unseen"]["either"]):
        u = r["unseen"]
        top = ", ".join(f"{k} ({v:,})" for k, v in u["mistaken_for"].items()) or "—"
        md.append(f"| {r['class']} | {u['flows']:,} | **{u['either']:.3f}** | {u['classifier']:.3f} | "
                  f"{u['anomaly']:.3f} | {r['seen_classifier']:.3f} | {r['benign_fpr']:.4f} | {top} |")
    either = pd.Series({r["class"]: r["unseen"]["either"] for r in rows})
    md += ["", f"Median detection of unseen classes: **{either.median():.3f}** "
           f"(classes at or above 0.9: {int((either >= 0.9).sum())} of {len(either)}). "
           "Detection rates are recall on attack flows; accuracy is not reported (rule 4).",
           f"Total run time {res['minutes']:.1f} min."]
    out.write_text("\n".join(md), encoding="utf-8")
    print(f"results in {out}")


if __name__ == "__main__":
    main()
