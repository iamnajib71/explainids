"""Cross-dataset evaluation (B14): train on one corrected CIC release, test on the other.

Usage:
  python scripts/cross_dataset_eval.py data/processed/cicids2017.parquet data/processed/csecicids2018.parquet \
      --model lgbm --cap 60000 --results docs/results/cross_dataset.md

Both datasets are globally deduplicated and split chronologically per class (as in train_baseline.py).
Every model is trained on its source's training split and scored on each dataset's test split, so the
in-domain row (A->A) and cross-domain row (B->A) share the same test flows. Two feature sets are
compared: all shared CICFlowMeter features, and a "portable" set without features that encode the
capture environment (destination port, TCP initial window sizes, minimum segment size).

Per direction we report multi-class metrics over the classes both datasets share, binary alert
quality for the classifier alone and for the deployed rule (classifier OR Isolation Forest outlier),
per-class detection rates, and the overlap of global SHAP top-10 features between source and target.
"""
import argparse
import json
import time
from pathlib import Path

import pandas as pd

from ids.data import BENIGN, LABEL_COL, dedup_global, feature_columns, stratified_sample, temporal_split
from ids.evaluate import binary_pr_auc, binary_report, report
from ids.explain import global_importance, rank_agreement
from ids.models import Detector

ENV_SPECIFIC = ["Dst Port", "FWD Init Win Bytes", "Bwd Init Win Bytes", "Fwd Seg Size Min"]


def load(path: str, cap: int) -> dict:
    df = dedup_global(pd.read_parquet(path))
    train, val, test = temporal_split(df)
    return {"name": Path(path).stem, "rows": len(df), "train": stratified_sample(train, cap),
            "val": val, "test": test, "classes": sorted(df[LABEL_COL].unique())}


def fit(src: dict, feats: list[str], model: str) -> Detector:
    tr, va = src["train"], src["val"]
    det = Detector(model).fit(tr[feats], tr[LABEL_COL])
    det.fit_anomaly(tr[tr[LABEL_COL] == BENIGN][feats])
    det.tune_anomaly_threshold(va[va[LABEL_COL] == BENIGN][feats])
    return det


def score(det: Detector, src: dict, tgt: dict, feats: list[str]) -> dict:
    X, y = tgt["test"][feats], tgt["test"][LABEL_COL]
    pred = det.predict(X)
    _, outlier = det.anomaly(X)
    shared = sorted(set(src["classes"]) & set(tgt["classes"]))
    rep = report(y, pred, sorted(set(det.classes) | set(tgt["classes"])))
    per = rep["per_class"]
    detected = pd.Series(pred != BENIGN, index=y.index).groupby(y).mean()
    caught = pd.Series((pred != BENIGN) | outlier, index=y.index).groupby(y).mean()
    rows = [{"class": c, "support": int(per.loc[c, "support"]), "seen_in_training": c in det.classes,
             "f1": float(per.loc[c, "f1"]), "detected": float(detected[c]), "detected_with_anomaly": float(caught[c])}
            for c in tgt["classes"]]
    return {
        "source": src["name"], "target": tgt["name"], "test_rows": len(y),
        "macro_shared": per.loc[[c for c in shared if per.loc[c, "support"] > 0],
                                ["precision", "recall", "f1"]].mean().to_dict(),
        "classifier": binary_report(y, pred != BENIGN),
        "with_anomaly": binary_report(y, (pred != BENIGN) | outlier),
        "pr_auc": binary_pr_auc(y, 1 - det.predict_proba(X)[:, det.benign_index]),
        "per_class": rows,
    }


def shap_shift(det: Detector, src: dict, tgt: dict, feats: list[str], k: int = 10) -> dict:
    a = [f["feature"] for f in global_importance(det, src["test"][feats], k=k)]
    b = [f["feature"] for f in global_importance(det, tgt["test"][feats], k=k)]
    return {"source_top": a, "target_top": b, "jaccard": rank_agreement(a, b)}


def fmt(v: float) -> str:
    return "n/a" if v != v else f"{v:.3f}"


def to_markdown(res: dict, cmd: str) -> str:
    ds = res["datasets"]
    md = ["# Cross-dataset evaluation", "",
          f"Generated by `{cmd}` on {res['generated']}. Model: **{res['model'].upper()}**, training capped at "
          f"{res['cap']:,} flows per class. Data globally deduplicated, then split chronologically per class "
          "(70/10/20). Each row trains on the source's training split and scores the target's test split, so "
          "rows with the same target use identical test flows.", "",
          "| Dataset | Rows after dedup | Train (capped) | Test | Classes |", "|---|---|---|---|---|"]
    md += [f"| {d['name']} | {d['rows']:,} | {d['train']:,} | {d['test']:,} | {d['classes']} |" for d in ds]
    if res.get("benign_note"):
        md += ["", res["benign_note"]]
    for fs, runs in res["runs"].items():
        md += ["", f"## Feature set: {fs} ({len(res['features'][fs])} features)", "",
               "| Source → target | Macro F1 (shared classes) | Alert P | Alert R | Alert F1 | Benign FPR | "
               "R with anomaly | FPR with anomaly | PR-AUC |", "|---|---|---|---|---|---|---|---|---|"]
        for r in runs:
            c, a = r["classifier"], r["with_anomaly"]
            md.append(f"| {r['source']} → {r['target']} | {fmt(r['macro_shared']['f1'])} | {fmt(c['precision'])} | "
                      f"{fmt(c['recall'])} | {fmt(c['f1'])} | {c['fpr']:.4f} | {fmt(a['recall'])} | {a['fpr']:.4f} | "
                      f"{fmt(r['pr_auc'])} |")
        for r in runs:
            if r["source"] == r["target"]:
                continue
            md += ["", f"### {fs}: {r['source']} → {r['target']}, per class", "",
                   "| Class | Test flows | Seen in training | F1 | Flagged as attack | Flagged incl. anomaly |",
                   "|---|---|---|---|---|---|"]
            md += [f"| {p['class']} | {p['support']:,} | {'yes' if p['seen_in_training'] else 'no'} | {fmt(p['f1'])} | "
                   f"{fmt(p['detected'])} | {fmt(p['detected_with_anomaly'])} |" for p in r["per_class"]]
    md += ["", "## Explanation shift (global SHAP top-10, all features)", "",
           "| Model trained on | Top-10 on own test | Top-10 on other dataset | Jaccard |", "|---|---|---|---|"]
    md += [f"| {s['trained_on']} | {', '.join(s['source_top'])} | {', '.join(s['target_top'])} | {s['jaccard']:.2f} |"
           for s in res["shap_shift"]]
    md += ["", "For BENIGN rows, *Flagged* columns are false-positive rates. Accuracy is not reported (rule 4).",
           f"Total run time {res['minutes']:.1f} min."]
    return "\n".join(md)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("a")
    ap.add_argument("b")
    ap.add_argument("--model", default="lgbm")
    ap.add_argument("--cap", type=int, default=60000)
    ap.add_argument("--results", default="docs/results/cross_dataset.md")
    args = ap.parse_args()

    t0 = time.perf_counter()
    data = [load(args.a, args.cap), load(args.b, args.cap)]
    shared = [f for f in feature_columns(data[0]["test"]) if f in set(feature_columns(data[1]["test"]))]
    feature_sets = {"all": shared, "portable": [f for f in shared if f not in ENV_SPECIFIC]}
    res = {"generated": time.strftime("%Y-%m-%d"), "model": args.model, "cap": args.cap,
           "features": feature_sets, "runs": {}, "shap_shift": [],
           "datasets": [{"name": d["name"], "rows": d["rows"], "train": len(d["train"]), "test": len(d["test"]),
                         "classes": len(d["classes"])} for d in data]}
    meta = Path(args.b).with_suffix(".json")
    if meta.exists():
        frac = json.loads(meta.read_text())["benign_frac"]
        res["benign_note"] = (f"{data[1]['name']} keeps every attack flow but only a {frac:.0%} random sample of "
                              "benign flows (seed 42), so its alert precision is optimistic; recall and FPR are unaffected.")
    for fs, feats in feature_sets.items():
        res["runs"][fs] = []
        for src in data:
            det = fit(src, feats, args.model)
            for tgt in data:
                r = score(det, src, tgt, feats)
                res["runs"][fs].append(r)
                print(f"[{fs}] {src['name']} -> {tgt['name']}: alert R {r['classifier']['recall']:.3f} "
                      f"FPR {r['classifier']['fpr']:.4f} | macro F1 shared {r['macro_shared']['f1']:.3f}", flush=True)
            if fs == "all":
                other = data[1] if src is data[0] else data[0]
                res["shap_shift"].append({"trained_on": src["name"], **shap_shift(det, src, other, feats)})
    res["minutes"] = (time.perf_counter() - t0) / 60

    out = Path(args.results)
    out.parent.mkdir(parents=True, exist_ok=True)
    cmd = (f"python scripts/cross_dataset_eval.py {args.a} {args.b} --model {args.model} --cap {args.cap}")
    out.write_text(to_markdown(res, cmd), encoding="utf-8")
    out.with_suffix(".json").write_text(json.dumps(res, indent=1, default=float), encoding="utf-8")
    print(f"results in {out} and {out.with_suffix('.json')}")


if __name__ == "__main__":
    main()
